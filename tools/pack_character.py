#!/usr/bin/env python3
"""Export the generated RGBA character to an LVGL flash image (no PNG runtime)."""
from pathlib import Path
from PIL import Image
ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'assets/character/rebot-rs-body-v2.png'
with Image.open(source) as image:
    image = image.convert('RGBA')
    # Ignore sub-visible alpha noise only when determining the export bounds.
    bounds = image.getchannel('A').point(lambda value: 255 if value > 8 else 0).getbbox()
    image = image.crop(bounds).resize((146, 176), getattr(Image, 'Resampling', Image).LANCZOS)
    data = image.tobytes('raw', 'BGRA')
lines = ['/* Generated by tools/pack_character.py. */', '#include "character_asset.h"',
         'static const uint8_t pixels[] = {']
for offset in range(0, len(data), 24):
    lines.append('    ' + ','.join(f'0x{value:02x}' for value in data[offset:offset+24]) + ',')
lines.extend(['};', 'const lv_image_dsc_t rb_character_body = {',
              '    .header = {.magic=LV_IMAGE_HEADER_MAGIC, .cf=LV_COLOR_FORMAT_ARGB8888, .w=146, .h=176, .stride=584},',
              '    .data_size=sizeof(pixels), .data=pixels,', '};', ''])
(ROOT/'main/character_asset.c').write_text('\n'.join(lines))
print(f'Packed {len(data)} bytes of flash image data from {source.name}')
