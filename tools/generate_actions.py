#!/usr/bin/env python3
"""Validate the single source of action data and emit a flash-resident C table."""
import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
IDS = ["LOOK", "NUZZLE", "SHY", "DANCE", "PUZZLED", "DOZE"]
FACES = {"IDLE", "HAPPY", "CURIOUS", "RELAXED", "SHY", "PUZZLED", "DROWSY", "SLEEP", "STOP"}

def generate():
    data = json.loads((ROOT / "config/actions.json").read_text())
    assert data["schema_version"] == 1
    assert data["units"] == "degrees_relative_to_calibrated_neutral"
    assert [a["id"] for a in data["actions"]] == IDS
    lines = ['/* Generated by tools/generate_actions.py; edit config/actions.json. */',
             '#include "rb_core.h"', 'const rb_action_t rb_actions[RB_ACTION_COUNT] = {']
    for action in data["actions"]:
        frames = action["frames"]
        assert 1 <= len(frames) <= 8
        assert action["name"].isascii() and action["name"].isidentifier()
        previous = 0
        lines.append(f'    [RB_{action["id"]}] = {{.name="{action["name"]}", .count={len(frames)}, .frames={{')
        for frame in frames:
            ms, pose, face = frame["ms"], frame["pose"], frame["face"]
            assert isinstance(ms, int) and 0 < ms <= 60000 and ms > previous
            assert len(pose) == 7 and all(isinstance(v, (int, float)) and math.isfinite(v) and abs(v) <= 8 for v in pose)
            assert face in FACES
            values = ','.join(f'{float(v):.4f}f' for v in pose)
            lines.append(f'        {{.at_ms={ms}, .offset_deg={{{values}}}, .face=RB_FACE_{face}}},')
            previous = ms
        assert all(v == 0 for v in frames[-1]["pose"]), "Every preview action must return to neutral"
        lines.append('    }},')
    lines.append('};')
    return '\n'.join(lines) + '\n'

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'components/rebuddy_core/src/rb_actions.c'
    source = generate()
    if args.check:
        if not output.exists() or output.read_text() != source:
            raise SystemExit('Action table is stale: run python3 tools/generate_actions.py')
        print('Action schema and generated table: OK')
    else:
        output.write_text(source)
        print(f'Generated {output.relative_to(ROOT)}')

if __name__ == '__main__':
    main()
