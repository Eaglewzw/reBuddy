#!/usr/bin/env python3
"""Compile checked PC daily plans into C5 data. Offline only; never opens CAN."""
import argparse
import json
import hashlib
import math
from pathlib import Path
import numpy as np
from rs_daily_prepare import load_bundle, Clap, BUNDLE
from rs_gravity_record import ROOT, DEFAULT_CALIBRATION, DEFAULT_URDF, CAPS, digest
from rs_gravity_play import KP, KD

OUTPUT=ROOT/'components/rebuddy_core/src/rb_daily_data.c'
REPORT=ROOT/'assets/verification/daily_c5_mapping.json'
IDS={'IDLE':0,'PROBE':1,'NUZZLE':2,'TILT':3,'HAPPY':6,'REST':7,'SLEEP':9,'WAKE':8}

def f(value):
    value=float(np.float32(value))
    if not math.isfinite(value):raise ValueError('nonfinite exported coefficient')
    s=format(value,'.9g')
    return s+('f' if '.' in s or 'e' in s else '.0f')

def pieces(curve):
    if isinstance(curve,Clap):
        boundaries=np.unique(np.r_[np.arange(5)*curve.half_s,curve.sway_times,
                                    curve.sway_times+2*curve.half_s])
    else:
        boundaries=np.unique(curve.spline.t)/curve.scale
    out=[]
    for begin,end in zip(boundaries[:-1],boundaries[1:]):
        if end-begin<1e-9:continue
        if isinstance(curve,Clap):
            # Both synchronized channels are piecewise quintics. Interior
            # points avoid choosing the neighbouring polynomial at a boundary.
            u=np.linspace(.05,.95,6)
            q=np.array([curve.at(begin+(end-begin)*x)[0] for x in u])
            coefficients=np.linalg.solve(np.polynomial.polynomial.polyvander(u,5),q).T
        else:
            # Evaluate inside the interval: roundoff at a knot may otherwise
            # select its left-hand fifth derivative and corrupt the next piece.
            center=(begin+end)*.5*curve.scale
            centered=np.array([curve.spline(center,nu=k)*
                                ((end-begin)*curve.scale)**k/math.factorial(k) for k in range(6)]).T
            shift=np.polynomial.Polynomial([-.5,1.])
            coefficients=np.array([np.pad(np.polynomial.Polynomial(row)(shift).coef,
                                  (0,6-len(np.polynomial.Polynomial(row)(shift).coef))) for row in centered])
        out.append((float(begin),float(end),coefficients))
    return out

def render():
    manifest,plans,_,identity=load_bundle(DEFAULT_CALIBRATION,DEFAULT_URDF)
    gifs=json.loads((ROOT/'assets/gifs/daily/manifest.json').read_text())['clips']
    assert [g['id'] for g in gifs]==list(IDS)
    lines=['/* Generated by tools/export_daily_c5.py; do not edit. No motor I/O. */',
           '#include "rb_daily.h"',
           'const char rb_daily_calibration_sha256[]="'+identity['calibration_sha256']+'";',
           'const char rb_daily_urdf_sha256[]="'+identity['urdf_sha256']+'";',
           'const rb_daily_policy_t rb_daily_policy={'+','.join(
               '{'+','.join(map(f,x))+'}' for x in (KP,KD,CAPS))+',0.5f,1.0f,1.0f,2.0f,1.0f,3.0f,3.0f,20u,100u};']
    entries=[];mapping=[]
    for index,gif in enumerate(gifs):
        name=gif['id'];plan=plans.get(name);item=manifest['actions'][name]
        gif_path=ROOT/'assets/gifs/daily'/gif['file']
        if digest(gif_path)!=gif['sha256']:raise ValueError('daily GIF hash mismatch')
        segments=[];stages=[];offset=0.
        if plan:
            for label,curve in plan.stages:
                stages.append(dict(name=label,start_s=offset,duration_s=curve.duration))
                segments.extend((a+offset,b+offset,c) for a,b,c in pieces(curve))
                offset+=curve.duration
        anchor=manifest['zero_rad'] if name=='SLEEP' else manifest['idle_rad']
        state={'ATTENTIVE_ENABLED':0,'ZERO_ENABLED':1,'ZERO_DISABLED':2}[item['exit']]
        sync=[(0.,0.),(offset,float(gif['duration_ms']))] if plan else []
        if name=='HAPPY':
            # Authored 8-second GIF: unfold 0..2s, two claps 2..6s, return 6..8s.
            # Initial approach holds the idle frame; no invented motor motion.
            sync=[(0.,0.),(stages[1]['start_s'],0.),(stages[2]['start_s'],2000.),
                  (stages[3]['start_s'],6000.),(offset,8000.)]
        if segments:
            lines.append(f'static const rb_daily_piece_t {name}_pieces[]={{')
            for a,b,c in segments:
                lines.append('{'+f(a)+','+f(b)+',{'+','.join('{'+','.join(map(f,row))+'}' for row in c)+'}},')
            lines.append('};')
            lines.append(f'static const rb_daily_sync_t {name}_sync[]={{'+','.join('{'+f(a)+','+f(b)+'}' for a,b in sync)+'};')
        entries.append('{'+','.join([str(IDS[name]),str(index),str(state),'true' if not plan else 'false',
                        json.dumps(name),json.dumps(gif['file'],ensure_ascii=False),f(offset),str(round(offset*1000))+'u',
                        name+'_pieces' if segments else '0',str(len(segments)),name+'_sync' if sync else '0',str(len(sync)),
                        str(gif['duration_ms']),'{'+','.join(map(f,anchor))+'}'])+'}')
        mapping.append(dict(id=name,pet_id=IDS[name],gif_index=index,gif=gif['file'],gif_sha256=gif['sha256'],
                            motion_duration_s=offset,loop=not bool(plan),end_state=item['exit'],
                            stages=stages,sync=[dict(motion_s=a,gif_ms=b) for a,b in sync],
                            plan_sha256=item.get('plan_sha256'),pieces=len(segments)))
    lines.append('const rb_daily_action_t rb_daily_actions[8]={'+',\n'.join(entries)+'};')
    code='\n'.join(lines)+'\n'
    report=dict(schema='rebuddy.daily.c5.mapping.v1',source_manifest_sha256=digest(BUNDLE/'manifest.json'),
                data_sha256=hashlib.sha256(code.encode()).hexdigest(),generator_sha256=digest(Path(__file__)),
                calibration_sha256=identity['calibration_sha256'],urdf_sha256=identity['urdf_sha256'],
                status='native_CAN_execution_opt_in; boot_SLEEP_click_arrow_to_WAKE; hardware_not_tested',
                native_execution_available=True,
                hardware_accepted=False,motor_output_enabled=False,torque_budget_nm=CAPS.tolist(),actions=mapping)
    return code,json.dumps(report,ensure_ascii=False,indent=2)+'\n'

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true')
    args=parser.parse_args();code,report=render()
    for path,content in ((OUTPUT,code),(REPORT,report)):
        if args.check:
            if not path.exists() or path.read_text()!=content:raise SystemExit(f'stale C5 daily export: {path}')
        else:path.write_text(content)
    print('C5 daily mapping: 8 actions, latest trajectories and GIF timing; no CAN I/O')
if __name__=='__main__':main()
